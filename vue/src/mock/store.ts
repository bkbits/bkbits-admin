/* ------------------------------ 工具 ------------------------------ */
function daysAgo(n: number, hour = 9, minute = 30): string {
  const d = new Date();
  d.setDate(d.getDate() - n);
  const p = (x: number) => String(x).padStart(2, "0");
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(hour)}:${p(minute)}:${p((n * 7) % 60)}`;
}

